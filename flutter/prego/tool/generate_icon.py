#!/usr/bin/env python3
"""Generate every Prego launcher icon from the single design below.

Run from anywhere (requires Pillow): python3 flutter/prego/tool/generate_icon.py

Shapes use Android's 108dp adaptive-icon grid. Launchers mask that canvas and
only guarantee the centered 66dp circle, so the stick must stay inside it.
"""

from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "android/app/src/main/res"
IOS = ROOT / "ios/Runner/Assets.xcassets/AppIcon.appiconset"

GRID = 108
TILT = 20
SHADOW_DROP = 3.5
CENTER = GRID / 2

# Prego design system: dye, dye-deep, stick-body, stick-cap, stick-rib, stick-window.
BACKGROUND = "#B50E62"
SHADOW = "#7D0A44"
BODY = "#FBFFFD"
CAP = "#7FE0B8"
RIB = "#3FBF92"
WINDOW = "#DCF5E7"
LINE = "#B50E62"

# Upright stick, tilted around the canvas center: (x, y, width, height, radius).
BODY_RECT = (43.5, 23, 21, 62, 10.5)
CAP_RECT = (43.5, 67, 21, 18, 10.5)
CAP_SEAM = (43.5, 67, 21, 8, 0)  # Squares off the top of the rounded cap.
RIBS = [(48.5, 72, 11, 2.3, 1.15), (48.5, 77, 11, 2.3, 1.15)]
WINDOW_RECT = (47, 33, 14, 27, 4.5)
LINES = [(49.5, 39, 9, 3.8, 1.9), (49.5, 49, 9, 3.8, 1.9)]

LAYERS = [
    (BODY_RECT, BODY),
    (CAP_RECT, CAP),
    (CAP_SEAM, CAP),
    *[(rib, RIB) for rib in RIBS],
    (WINDOW_RECT, WINDOW),
    *[(line, LINE) for line in LINES],
]

LEGACY_SIZES = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}
IOS_SIZES = {
    "20x20@1x": 20, "20x20@2x": 40, "20x20@3x": 60,
    "29x29@1x": 29, "29x29@2x": 58, "29x29@3x": 87,
    "40x40@1x": 40, "40x40@2x": 80, "40x40@3x": 120,
    "60x60@2x": 120, "60x60@3x": 180,
    "76x76@1x": 76, "76x76@2x": 152,
    "83.5x83.5@2x": 167, "1024x1024@1x": 1024,
}  # fmt: skip


def rrect_path(rect):
    x, y, w, h, r = rect
    if r == 0:
        return f"M{x},{y}h{w}v{h}h{-w}z"
    return (
        f"M{x + r},{y}h{w - 2 * r}a{r},{r} 0 0 1 {r},{r}v{h - 2 * r}"
        f"a{r},{r} 0 0 1 {-r},{r}h{-(w - 2 * r)}a{r},{r} 0 0 1 {-r},{-r}"
        f"v{-(h - 2 * r)}a{r},{r} 0 0 1 {r},{-r}z"
    )


def fill_path(data, color, extra=""):
    return f'<path android:fillColor="{color}"{extra} android:pathData="{data}" />'


def tilted_group(paths, translate_y=0):
    translate = f' android:translateY="{translate_y}"' if translate_y else ""
    body = "\n        ".join(paths)
    return (
        f'    <group android:pivotX="{CENTER:g}" android:pivotY="{CENTER:g}" '
        f'android:rotation="{TILT}"{translate}>\n        {body}\n    </group>'
    )


def vector(groups):
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- Generated by tool/generate_icon.py. -->\n'
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        f'    android:width="{GRID}dp"\n    android:height="{GRID}dp"\n'
        f'    android:viewportWidth="{GRID}"\n    android:viewportHeight="{GRID}">\n'
        + "\n".join(groups)
        + "\n</vector>\n"
    )


def foreground_xml():
    return vector(
        [
            tilted_group(
                [fill_path(rrect_path(BODY_RECT), SHADOW)], SHADOW_DROP
            ),
            tilted_group([fill_path(rrect_path(r), c) for r, c in LAYERS]),
        ]
    )


def monochrome_xml():
    """Silhouette for Android 13+ themed icons: only alpha is used."""
    cutout = rrect_path(BODY_RECT) + rrect_path(WINDOW_RECT)
    paths = [fill_path(cutout, "#FFFFFFFF", ' android:fillType="evenOdd"')]
    paths += [fill_path(rrect_path(line), "#FFFFFFFF") for line in LINES]
    return vector([tilted_group(paths)])


def draw_stick(size):
    """Render the foreground on a transparent `size` square of the 108dp grid."""
    scale = size / GRID

    def scaled(rect):
        x, y, w, h, r = rect
        return [x * scale, y * scale, (x + w) * scale, (y + h) * scale], r * scale

    def layer(items):
        image = Image.new("RGBA", (size, size), (0, 0, 0, 0))
        draw = ImageDraw.Draw(image)
        for rect, color in items:
            box, radius = scaled(rect)
            draw.rounded_rectangle(box, radius, fill=color)
        return image.rotate(-TILT, Image.Resampling.BICUBIC)

    shadow = layer([(BODY_RECT, SHADOW)])
    canvas = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    canvas.alpha_composite(shadow, (0, round(SHADOW_DROP * scale)))
    canvas.alpha_composite(layer(LAYERS))
    return canvas


def master(size=4096):
    """Full-bleed square: the adaptive canvas cropped to its visible 72dp."""
    full = round(size * GRID / 72)
    image = Image.new("RGBA", (full, full), BACKGROUND)
    image.alpha_composite(draw_stick(full))
    inset = (full - size) // 2
    return image.crop((inset, inset, inset + size, inset + size))


def resized(image, size):
    return image.resize((size, size), Image.Resampling.LANCZOS)


def legacy(image, size):
    """Android 7.x has no masking, so the PNG brings its own rounded corners."""
    scale = 8
    mask = Image.new("L", (size * scale, size * scale), 0)
    radius = size * scale * 0.18
    ImageDraw.Draw(mask).rounded_rectangle(
        [0, 0, size * scale - 1, size * scale - 1], radius, fill=255
    )
    out = resized(image, size)
    out.putalpha(mask.resize((size, size), Image.Resampling.LANCZOS))
    return out


def main():
    anydpi = RES / "mipmap-anydpi-v26"
    anydpi.mkdir(exist_ok=True)
    (anydpi / "ic_launcher.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        '    <background android:drawable="@color/ic_launcher_background" />\n'
        '    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n'
        '    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />\n'
        "</adaptive-icon>\n"
    )
    (RES / "values/ic_launcher_background.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n<resources>\n'
        f'    <color name="ic_launcher_background">{BACKGROUND}</color>\n</resources>\n'
    )
    (RES / "drawable/ic_launcher_foreground.xml").write_text(foreground_xml())
    (RES / "drawable/ic_launcher_monochrome.xml").write_text(monochrome_xml())

    art = master()
    for density, size in LEGACY_SIZES.items():
        legacy(art, size).save(RES / f"mipmap-{density}/ic_launcher.png", optimize=True)
    opaque = art.convert("RGB")  # App Store icons must not contain alpha.
    for name, size in IOS_SIZES.items():
        resized(opaque, size).save(IOS / f"Icon-App-{name}.png", optimize=True)
    resized(opaque, 1024).save(ROOT / "assets/Icon.png", optimize=True)


if __name__ == "__main__":
    main()
