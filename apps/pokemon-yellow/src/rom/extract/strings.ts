export function extractStrings(rom: Rom): Record<string, string> {
  const out: Record<string, string> = {};
  for (const l of UI_STRING_LABELS) {
    if (!hasSymbol(l)) throw new Error(`UI string label missing: ${l}`);
    out[l] = decodeString(rom, sym(l), 80);
  }
  // every gym's LoadGymLeaderAndCityName strings (<Gym>_Script.CityName / .LeaderName)
  for (const l of allRomLabels()) if (/Gym_Script\.(CityName|LeaderName)$|^CinnabarGymSetMapAndTiles\.(CityName|LeaderName)$/.test(l)) out[l] = decodeString(rom, sym(l), 20);
  return out;
}
